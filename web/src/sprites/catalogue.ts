/**
 * The sprite catalogue.
 *
 * Each creature is a 14x14 grid of characters. A digit indexes that sprite's
 * palette, '.' is transparent. Kept as text so a sprite can be read, diffed and
 * nudged by hand, with no binary assets in the repo.
 *
 * Motion is CSS rather than extra frames: one drawing per creature, animated by
 * transform. Half as much pixel data to get wrong, and the movement interpolates
 * instead of stepping.
 */

export interface SpriteDef {
  id: string
  name: string
  palette: string[]
  rows: string[]
}

