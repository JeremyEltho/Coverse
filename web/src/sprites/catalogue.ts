export const SPRITE_IDS = SPRITES.map((s) => s.id)

const byId = new Map(SPRITES.map((s) => [s.id, s]))

export function spriteById(id: string | undefined): SpriteDef {
  if (id === ASSISTANT_SPRITE.id) return ASSISTANT_SPRITE
  return (id && byId.get(id)) || SPRITES[0]
}

/** A stable pick for someone who never chose one. */
export function spriteForSeed(seed: string): SpriteDef {
  let hash = 0
  for (let i = 0; i < seed.length; i += 1) hash = (hash * 31 + seed.charCodeAt(i)) | 0
  return SPRITES[Math.abs(hash) % SPRITES.length]
}
